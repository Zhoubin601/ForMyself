import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import assert from 'node:assert/strict'
import { spawn } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { connect, store, pause, uiSet } from '../app-audit-20261003/cdp.mjs'

const qa = path.dirname(fileURLToPath(import.meta.url))
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'formyself-unlock-'))
const browser = spawn('C:/Program Files/Google/Chrome/Application/chrome.exe', ['--headless=new', '--remote-debugging-port=0', `--user-data-dir=${profile}`, '--no-first-run', '--disable-background-networking', 'about:blank'], { windowsHide: true, stdio: 'ignore' })
const baseline = process.argv.includes('--baseline')
const results = { date: '2026-10-19', baseline, syntheticDataOnly: true, tests: [], timings: [] }
let c
try {
  const portFile = path.join(profile, 'DevToolsActivePort')
  for (let i = 0; i < 100 && !fs.existsSync(portFile); i++) await pause(100)
  process.env.QA_CDP_PORT = fs.readFileSync(portFile, 'utf8').split('\n')[0]
  c = await connect()
  await c.send('Network.enable')
  await c.send('Network.setBlockedURLs', { urls: ['https://*'] })
  await c.send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  await c.send('Page.navigate', { url: 'http://127.0.0.1:5193/' })
  await c.until(`!!${store('auth')}?.isDataLoaded && !!${store('settings')}?.isDataLoaded`)
  await c.evaluate(uiSet('.lock-screen input', 'Synthetic-QA-2026'))
  await c.evaluate(`document.querySelector('.lock-btn').click()`)
  await c.until(`!${store('auth')}.isLocked && !!${store('chat')}?.isDataLoaded`)
  await pause(500)
  results.timings = await c.evaluate(`performance.getEntriesByType('measure').map(x=>({name:x.name,duration:x.duration}))`)
  results.tests.push('first setup and unified data load')
  assert.equal(await c.evaluate(`${store('passwordVault')}.isDataLoaded`), true)
  if (!baseline) {
    const record = name => { results.tests.push(name); console.log('PASS ' + name) }
    const click = selector => c.evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`)
    const confirmPassword = async (password = 'Synthetic-QA-2026') => {
      await c.until(`!!document.querySelector('.feedback-input[type=password]')`)
      await c.evaluate(uiSet('.feedback-input', password))
      await click('.feedback-confirm')
    }
    const reload = async () => {
      const old = await c.evaluate('performance.timeOrigin')
      await c.send('Page.reload', { ignoreCache: true })
      await c.until(`performance.timeOrigin !== ${old} && !!${store('settings')}?.isDataLoaded && !!${store('auth')}?.isDataLoaded`)
    }
    await c.evaluate(`${store('passwordVault')}.addRecord({appName:'Synthetic website', account:'test-account',password:'fake-secret',category:'QA'}); ${store('chat')}.appendMessage('user','Synthetic chat record')`)
    await c.evaluate(`${store('chat')}.flush()`)
    await c.evaluate(`${store('settings')}.openGeneralSettingsSection('security')`)
    await c.until(`!!document.querySelector('#require-app-unlock')`)
    await click('#require-app-unlock')
    await c.until(`!!document.querySelector('.feedback-input')`)
    await click('.feedback-cancel')
    assert.equal(await c.evaluate(`${store('settings')}.requireAppUnlock`), true)
    record('cancel disabling entry verification retains old setting')
    await click('#require-app-unlock')
    await confirmPassword('wrong-synthetic-password')
    await c.until(`document.querySelector('.feedback-message')?.textContent.includes('未通过')`)
    await click('.feedback-confirm')
    assert.equal(await c.evaluate(`${store('settings')}.requireAppUnlock`), true)
    record('wrong password cannot disable entry verification')
    await click('#require-app-unlock')
    await confirmPassword()
    await c.until(`${store('settings')}.requireAppUnlock === false`)
    await c.evaluate(`${store('settings')}.flushPendingSettingsWrites()`)
    await c.send('Page.addScriptToEvaluateOnNewDocument', { source: `new MutationObserver((_,o)=>{if(!document.querySelector('.app-wrapper'))return;window.__firstSecurity={locked:!!document.querySelector('.lock-screen'),at:performance.now()};o.disconnect()}).observe(document,{childList:true,subtree:true})` })
    await reload()
    await pause(350)
    assert.equal(await c.evaluate(`${store('auth')}.isLocked`), false)
    assert.equal(await c.evaluate(`${store('auth')}.savedMasterPwd`), '')
    assert.equal(await c.evaluate('window.__firstSecurity.locked'), false)
    assert.equal(await c.evaluate(`!!${store('passwordVault')}?.isDataLoaded || !!${store('chat')}?.isDataLoaded`), false)
    results.directEntryTimings = await c.evaluate(`({firstFrame:window.__firstSecurity.at, measures:performance.getEntriesByType('measure').map(x=>({name:x.name,duration:x.duration}))})`)
    record('cold reload directly enters home without lock flash or protected decryption')
    for (const view of ['todo', 'schedule', 'mood', 'settings']) {
      await c.evaluate(`${store('settings')}.switchView('${view}')`)
      await pause(180)
    }
    assert.equal(await c.evaluate(`!!${store('passwordVault')}?.isDataLoaded || !!${store('chat')}?.isDataLoaded`), false)
    record('ordinary pages and general settings do not decrypt protected data')
    await c.evaluate(`${store('settings')}.switchView('passwords')`)
    await c.until(`!!document.querySelector('.feedback-input')`)
    await click('.feedback-cancel')
    assert.equal(await c.evaluate(`${store('protectedAccess')}.status.passwords`), 'idle')
    await click('.protected-data-loading .button-primary')
    await confirmPassword()
    await c.until(`!!document.querySelector('.vault-view')`)
    assert.equal(await c.evaluate(`${store('passwordVault')}.records[0].appName`), 'Synthetic website')
    assert.equal(await c.evaluate(`!!${store('chat')}?.isDataLoaded`), false)
    record('password vault independently authenticates and decrypts only itself')
    await c.evaluate(`${store('settings')}.switchView('chat')`)
    await c.until(`${store('protectedAccess')}.status.chat === 'ready' && !!document.querySelector('.warm-home')`)
    assert.equal(await c.evaluate(`!!document.querySelector('.feedback-input')`), false)
    assert.equal(await c.evaluate(`${store('chat')}.messages.some(x=>x.content==='Synthetic chat record')`), true)
    record('chat decrypts independently and reuses a valid session')
    await c.evaluate(`${store('auth')}.expireSession({lockApp:false})`)
    await c.until(`!${store('chat')}.isDataLoaded && !document.querySelector('.warm-home')`)
    assert.equal(await c.evaluate(`${store('auth')}.isLocked`), false)
    assert.equal(await c.evaluate(`${store('chat')}.messages.length`), 0)
    record('session expiry clears protected state and unloads cached chat without locking ordinary pages')
    await c.evaluate(`${store('settings')}.openModuleSettings('chat')`)
    await confirmPassword()
    await c.until(`!!document.querySelector('.chat-settings-section')`)
    record('chat settings entry is guarded and becomes usable after decryption')
    await c.evaluate(`${store('settings')}.openGeneralSettingsSection('labels')`)
    await c.until(`!!document.querySelector('.taxonomy-card') && ${store('protectedAccess')}.status.passwords === 'ready'`)
    record('password category settings load the vault through the same guard')
    await c.evaluate(`${store('settings')}.openGeneralSettingsSection('security')`)
    await c.until(`!!document.querySelector('#require-app-unlock')`)
    for (const width of [320, 390, 1280]) {
      await c.send('Emulation.setDeviceMetricsOverride', { width, height: 844, deviceScaleFactor: 1, mobile: width < 900 })
      await pause(100)
      assert.equal(await c.evaluate('document.documentElement.scrollWidth > innerWidth'), false)
      const shot = await c.send('Page.captureScreenshot', { format: 'png' })
      fs.writeFileSync(path.join(qa, `${width}-security.png`), Buffer.from(shot.data, 'base64'))
    }
    record('security setting layouts fit 320/390/1280 widths')
    await click('#require-app-unlock')
    await c.until(`${store('settings')}.requireAppUnlock === true`)
    await reload()
    assert.equal(await c.evaluate(`${store('auth')}.isLocked`), true)
    await c.evaluate(uiSet('.lock-screen input', 'Synthetic-QA-2026'))
    await click('.lock-btn')
    await c.until(`${store('protectedAccess')}.status.chat === 'ready' && ${store('protectedAccess')}.status.passwords === 'ready'`)
    results.unifiedReloadTimings = await c.evaluate(`performance.getEntriesByType('measure').map(x=>({name:x.name,duration:x.duration}))`)
    record('re-enabled mode restores unified verification and decryption of both modules')
    await c.evaluate(`${store('auth')}.lockApp()`)
    await c.until(`!!document.querySelector('.lock-screen') && !${store('chat')}.isDataLoaded`)
    record('manual lock hides the app and releases protected data')
  }
  results.errors = c.events.filter(x => x.method === 'Runtime.exceptionThrown').map(x => x.params.exceptionDetails.text)
  assert.deepEqual(results.errors, [])
  fs.writeFileSync(path.join(qa, baseline ? 'baseline.json' : 'browser-results.json'), JSON.stringify(results, null, 2))
  console.log(JSON.stringify(results))
} finally {
  c?.close()
  browser.kill()
}
