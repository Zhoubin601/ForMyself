export function projectSettingsModel(providers, keys) {
  return Object.fromEntries(keys.map(key => {
    const candidates = providers.filter(provider => Object.hasOwn(provider, key)).map(provider => provider[key])
    if (!candidates.length) throw new Error(`MISSING_SETTINGS_FIELD:${key}`)
    if (candidates.some(value => value !== candidates[0])) throw new Error(`AMBIGUOUS_SETTINGS_FIELD:${key}`)
    return [key, candidates[0]]
  }))
}

